// Recursive release reconciliation for the Electron staging/package boundary.
// Uses Node built-ins only; the ASAR header is read directly so the verifier
// does not rely on a presence-only scan or an extra dependency.
// Usage: node scripts/verify-electron-reconciliation.mjs --asar <app.asar> [--staging <dir>] [--unpacked <dir>] [--extracted <dir>] [--out <manifest.json>] [--task <label>]
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const DESKTOP_MODULES = [
  "main.cjs",
  "preload.cjs",
  "account-browser.cjs",
  "chrome-browser.cjs",
  "worker-supervisor.cjs",
  "secret-chunks.cjs",
  "portable-env.cjs",
  "secure-store.cjs",
  "meta.cjs",
  "provider-models.cjs",
  "oauth-url.cjs",
  "security.cjs",
  "vertex-ai.cjs",
  "drive-media.cjs",
];
const WORKER_PYTHON_FILES = [
  "app_state_store.py",
  "automation_worker.py",
  "automation_worker_service.py",
  "control_plane_service.py",
  "generation_policy.py",
  "profile_database_migration.py",
];

const GENERATED_PACKAGE = {
  name: "signalflow-electron",
  productName: "SignalFlow",
  version: "0.1.0",
  description: "SignalFlow social marketing operating system",
  main: "desktop/main.cjs",
};

function parseArgs(argv) {
  const values = new Map();
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (token === "--help") {
      console.log("Usage: node scripts/verify-electron-reconciliation.mjs --asar <app.asar> [--staging <dir>] [--unpacked <dir>] [--extracted <dir>] [--out <manifest.json>] [--task <label>]");
      process.exit(0);
    }
    if (!token.startsWith("--")) throw new Error(`unknown argument: ${token}`);
    const value = argv[index + 1];
    if (!value || value.startsWith("--")) throw new Error(`missing value for ${token}`);
    values.set(token, value);
    index += 1;
  }
  return values;
}

function toPosix(value) {
  return value.split(path.sep).join("/").replaceAll("\\", "/");
}

function walkFiles(directory) {
  if (!fs.existsSync(directory)) return [];
  const files = [];
  const visit = (current, relative) => {
    const entries = fs.readdirSync(current, { withFileTypes: true }).sort((left, right) => left.name.localeCompare(right.name));
    for (const entry of entries) {
      const next = path.join(current, entry.name);
      const nextRelative = relative ? `${relative}/${entry.name}` : entry.name;
      if (entry.isDirectory()) visit(next, nextRelative);
      else if (entry.isFile()) files.push(toPosix(nextRelative));
      else if (entry.isSymbolicLink()) {
        try {
          if (fs.statSync(next).isFile()) files.push(toPosix(nextRelative));
        } catch {
          // Dangling links are not shipped application files.
        }
      }
    }
  };
  visit(directory, "");
  return files.sort();
}

function sha256(buffer) {
  return crypto.createHash("sha256").update(buffer).digest("hex");
}

function fileDetails(filePath) {
  if (!fs.existsSync(filePath) || !fs.statSync(filePath).isFile()) return null;
  const buffer = fs.readFileSync(filePath);
  return { bytes: buffer.length, sha256: sha256(buffer), buffer };
}

function generatedPackageBuffer() {
  return Buffer.from(`${JSON.stringify(GENERATED_PACKAGE, null, 2)}\n`);
}

function expectedFiles() {
  const expected = new Map();
  const add = (relative, sourcePath, sourceBuffer = null) => {
    if (expected.has(relative)) throw new Error(`duplicate expected path: ${relative}`);
    expected.set(relative, { sourcePath, sourceBuffer });
  };

  const distRoot = path.join(root, "dist");
  for (const relative of walkFiles(distRoot)) add(`dist/${relative}`, path.join(distRoot, relative));
  for (const filename of DESKTOP_MODULES) add(`desktop/${filename}`, path.join(root, "desktop", filename));
  add("worker-runtime/run-local-worker.mjs", path.join(root, "scripts", "run-local-worker.mjs"));
  for (const filename of WORKER_PYTHON_FILES) add(`worker-runtime/backend/${filename}`, path.join(root, "backend", filename));
  add("package.json", "generated by build-electron-staging.mjs", generatedPackageBuffer());
  return expected;
}

function parseAsar(asarPath, unpackedRoot) {
  const archive = fs.readFileSync(asarPath);
  if (archive.length < 16) throw new Error("ASAR_HEADER_TOO_SHORT");
  const jsonSize = archive.readUInt32LE(12);
  const jsonStart = 16;
  const jsonEnd = jsonStart + jsonSize;
  if (jsonEnd > archive.length) throw new Error("ASAR_HEADER_OUT_OF_BOUNDS");
  const header = JSON.parse(archive.subarray(jsonStart, jsonEnd).toString("utf8"));
  const dataOffset = jsonStart + Math.ceil(jsonSize / 4) * 4;
  const entries = new Map();
  const visit = (nodes, relative) => {
    for (const [name, node] of Object.entries(nodes ?? {})) {
      const child = relative ? `${relative}/${name}` : name;
      if (node && node.files) visit(node.files, child);
      else entries.set(toPosix(child), node ?? {});
    }
  };
  visit(header.files, "");

  const read = (relative) => {
    const node = entries.get(relative);
    if (!node) {
      const fallback = unpackedRoot ? fileDetails(path.join(unpackedRoot, relative)) : null;
      return fallback ? { location: `app.asar.unpacked/${relative}`, ...fallback } : null;
    }
    if (node.unpacked) {
      const details = unpackedRoot ? fileDetails(path.join(unpackedRoot, relative)) : null;
      return details ? { location: `app.asar.unpacked/${relative}`, ...details } : null;
    }
    const offset = Number(node.offset ?? 0);
    const size = Number(node.size);
    if (!Number.isSafeInteger(offset) || !Number.isSafeInteger(size) || offset < 0 || size < 0) throw new Error(`ASAR_INVALID_ENTRY: ${relative}`);
    const start = dataOffset + offset;
    const end = start + size;
    if (end > archive.length) throw new Error(`ASAR_ENTRY_OUT_OF_BOUNDS: ${relative}`);
    const buffer = archive.subarray(start, end);
    return { location: `app.asar/${relative}`, bytes: buffer.length, sha256: sha256(buffer), buffer };
  };
  return { entries, read };
}

function directoryDigest(directory) {
  const files = walkFiles(directory);
  const digest = crypto.createHash("sha256");
  let bytes = 0;
  for (const relative of files) {
    const buffer = fs.readFileSync(path.join(directory, relative));
    bytes += buffer.length;
    digest.update(`${relative}\0${buffer.length}\0`);
    digest.update(buffer);
    digest.update("\0");
  }
  return { bytes, files: files.length, sha256: digest.digest("hex") };
}

function sourceSnapshots() {
  const snapshots = {};
  const srcRoot = path.join(root, "src");
  for (const relative of walkFiles(srcRoot)) {
    if (!/\.(?:tsx|css)$/i.test(relative)) continue;
    const details = fileDetails(path.join(srcRoot, relative));
    snapshots[`src/${relative}`] = { bytes: details.bytes, sha256: details.sha256 };
  }
  return snapshots;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const asarPath = args.get("--asar");
  if (!asarPath) throw new Error("--asar is required");
  const task = args.get("--task") ?? "A07";
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/.test(task)) throw new Error("--task is invalid");
  const stagingRoot = path.resolve(args.get("--staging") ?? path.join(root, "dist-electron-staging"));
  const unpackedRoot = path.resolve(args.get("--unpacked") ?? path.join(path.dirname(path.resolve(asarPath)), "app.asar.unpacked"));
  const extractedRoot = args.has("--extracted") ? path.resolve(args.get("--extracted")) : null;
  const outputPath = args.has("--out") ? path.resolve(args.get("--out")) : null;
  const asarAbsolute = path.resolve(asarPath);
  const expected = expectedFiles();
  const archive = parseAsar(asarAbsolute, unpackedRoot);
  const stagedFiles = new Set(walkFiles(stagingRoot));
  const unpackedFiles = new Set(walkFiles(unpackedRoot));
  const archiveFiles = new Set([...archive.entries.keys()]);
  const records = [];
  const missing = [];
  const mismatched = [];

  for (const relative of [...expected.keys()].sort()) {
    const expectedEntry = expected.get(relative);
    const source = expectedEntry.sourceBuffer
      ? { bytes: expectedEntry.sourceBuffer.length, sha256: sha256(expectedEntry.sourceBuffer), buffer: expectedEntry.sourceBuffer }
      : fileDetails(expectedEntry.sourcePath);
    const staged = fileDetails(path.join(stagingRoot, relative));
    const packed = archive.read(relative);
    const sourceSha = source?.sha256 ?? null;
    const stagedSha = staged?.sha256 ?? null;
    const packedSha = packed?.sha256 ?? null;
    const match = Boolean(source && staged && packed && sourceSha === stagedSha && sourceSha === packedSha);
    if (!source || !staged || !packed) missing.push(relative);
    else if (!match) mismatched.push(relative);
    records.push({
      relative,
      sourceBytes: source?.bytes ?? null,
      sourceSha256: sourceSha,
      stagedBytes: staged?.bytes ?? null,
      stagedSha256: stagedSha,
      packedLocation: packed?.location ?? (archive.entries.get(relative)?.unpacked ? `app.asar.unpacked/${relative}` : `app.asar/${relative}`),
      packedBytes: packed?.bytes ?? null,
      packedSha256: packedSha,
      match,
    });
  }

  const unexpected = [...new Set([
    ...[...stagedFiles].filter((relative) => !expected.has(relative)),
    ...[...archiveFiles].filter((relative) => !expected.has(relative)),
    ...[...unpackedFiles].filter((relative) => !expected.has(relative)),
  ])].sort();

  const extractionRootExists = extractedRoot !== null && fs.existsSync(extractedRoot) && fs.statSync(extractedRoot).isDirectory();
  const extraction = { root: extractedRoot, rootMissing: extractedRoot !== null && !extractionRootExists, missing: [], mismatched: [], unexpected: [] };
  if (extractedRoot) {
    const extractedFiles = new Set(extractionRootExists ? walkFiles(extractedRoot) : []);
    for (const relative of [...expected.keys()].sort()) {
      if (extraction.rootMissing) {
        extraction.missing.push(relative);
        continue;
      }
      const extracted = fileDetails(path.join(extractedRoot, relative));
      const packed = archive.read(relative);
      if (!extracted) extraction.missing.push(relative);
      else if (!packed || extracted.sha256 !== packed.sha256) extraction.mismatched.push(relative);
    }
    extraction.unexpected = [...extractedFiles].filter((relative) => !expected.has(relative)).sort();
  }

  const appPath = path.dirname(path.dirname(path.dirname(asarAbsolute)));
  const packageRoot = path.dirname(path.dirname(path.dirname(path.dirname(asarAbsolute))));
  const executablePath = path.join(appPath, "Contents", "MacOS", "SignalFlow");
  const executable = fileDetails(executablePath);
  const packageDigest = fs.existsSync(packageRoot) ? directoryDigest(packageRoot) : null;
  const extractionFailed = extractedRoot !== null && (extraction.rootMissing || extraction.missing.length > 0 || extraction.mismatched.length > 0 || extraction.unexpected.length > 0);
  const allCompared = missing.length === 0 && unexpected.length === 0 && mismatched.length === 0 && !extractionFailed;
  const manifest = {
    schemaVersion: 1,
    task,
    status: allCompared ? "PASS" : "FAIL",
    repo: root,
    sourceRoot: root,
    stagingRoot,
    asar: { path: asarAbsolute, bytes: fs.statSync(asarAbsolute).size, sha256: sha256(fs.readFileSync(asarAbsolute)) },
    unpackedRoot,
    extractedRoot,
    package: {
      root: packageRoot,
      app: appPath,
      digest: packageDigest,
      executable: executable ? { path: executablePath, bytes: executable.bytes, sha256: executable.sha256 } : { path: executablePath, bytes: null, sha256: null },
    },
    electronVersion: JSON.parse(fs.readFileSync(path.join(root, "node_modules", "electron", "package.json"), "utf8")).version,
    expectedFiles: [...expected.keys()].sort(),
    sourceSnapshots: sourceSnapshots(),
    files: records,
    missing,
    unexpected,
    mismatched,
    allCompared,
    extraction,
    summary: { expected: records.length, matched: records.filter((record) => record.match).length, missing: missing.length, unexpected: unexpected.length, mismatched: mismatched.length, extractionMissing: extraction.missing.length, extractionUnexpected: extraction.unexpected.length, extractionMismatched: extraction.mismatched.length },
  };
  if (outputPath) {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, `${JSON.stringify(manifest, null, 2)}\n`);
  }
  console.log(JSON.stringify({ status: manifest.status, allCompared, summary: manifest.summary, missing, unexpected, mismatched, extraction }, null, 2));
  if (!allCompared) process.exitCode = 1;
}

try {
  main();
} catch (error) {
  console.error(`A07_RECONCILIATION_ERROR: ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 2;
}
